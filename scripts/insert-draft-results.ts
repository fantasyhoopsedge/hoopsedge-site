async function main() {
  const admin = createAdminClient();

  // Get game id
  const { data: game, error: gameErr } = await admin
    .from("dn_games")
    .select("id, status")
    .eq("slug", GAME_SLUG)
    .single();

  if (gameErr || !game) {
    console.error("Game not found:", gameErr?.message ?? "no row");
    process.exit(1);
  }
  console.log(`Game: ${GAME_SLUG} (${game.id}) — status: ${game.status}`);

  // Insert / upsert dn_results row
  const { error: resErr } = await admin
    .from("dn_results")
    .upsert(
      { game_id: game.id, picks: PICKS_2026 },
      { onConflict: "game_id" },
    );

  if (resErr) {
    console.error("Failed to insert dn_results:", resErr.message);
    process.exit(1);
  }
  console.log("dn_results row upserted. Running grader…");

  // Grade all predictions and set status → resolved
  const summary = await resolveDraftNight(GAME_SLUG);
  console.log(
    `Done. Graded ${summary.graded} prediction(s) across ${summary.miniGames} mini-game(s).`,
  );
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
